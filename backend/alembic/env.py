"""Alembic environment. The URL always comes from app.config (DATABASE_URL)."""

from __future__ import annotations

from logging.config import fileConfig

from sqlalchemy import engine_from_config, pool

from alembic import context
from app.config import Settings
from app.models import Base

config = context.config
if config.config_file_name is not None:
    # ``disable_existing_loggers=False`` is load-bearing, not tidiness.  The default is
    # True, which *disables every logger that already exists* — and this file is imported
    # into a process that has usually already imported half of ``app``, so a migration run
    # in-process (the test suite builds its schema this way, and ``keyup migrate`` shares
    # the interpreter with the code it is about to run) would silently switch off the
    # application's own logging for the rest of that process.  Nothing announces it: the
    # log lines simply stop.
    fileConfig(config.config_file_name, disable_existing_loggers=False)

# ``%`` is the interpolation character in alembic.ini, so a password containing one has to
# be escaped before it is handed over.
config.set_main_option("sqlalchemy.url", Settings().database_url.replace("%", "%%"))

target_metadata = Base.metadata


def include_object(obj, name, type_, reflected, compare_to) -> bool:  # noqa: ANN001
    """Keep reflected-only artifacts out of autogenerated migrations."""
    return True


def run_migrations_offline() -> None:
    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        include_object=include_object,
        compare_type=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            include_object=include_object,
            compare_type=True,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
